import { defineConfig } from "vite";
import react from "@vitejs/plugin-react";
import tailwindcss from "@tailwindcss/vite";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const ESTACION = "http://127.0.0.1:8787";

// `bun run ui:dev`: servidor de Vite con HMR de React (Fast Refresh) y la estación detrás: /api y /terrain van a la estación.
// `bun run ui:build`: un solo HTML autocontenido (estacion.html) que la estación sirve en /.
export default defineConfig(({ command }) => ({
  root: resolve(import.meta.dirname),
  // Solo al compilar (lib iife): en `ui:dev` React tiene que correr en modo desarrollo (avisos y Fast Refresh).
  define: command === "build" ? { "process.env.NODE_ENV": JSON.stringify("production") } : {},
  server: {
    host: "127.0.0.1",
    proxy: {
      "/api": { target: ESTACION, changeOrigin: true, headers: { origin: ESTACION } },
      "/terrain": { target: ESTACION, changeOrigin: true },
    },
  },
  build: {
    outDir: "dist",
    emptyOutDir: true,
    cssCodeSplit: false,
    lib: {
      entry: resolve(import.meta.dirname, "src/main.tsx"),
      name: "MuStation",
      formats: ["iife"],
      cssFileName: "style",
      fileName: () => "app.js",
    },
    rolldownOptions: {
      onwarn(warning, warn) {
        if (warning.code !== "MODULE_LEVEL_DIRECTIVE") warn(warning);
      },
    },
  },
  plugins: [
    react(),
    tailwindcss(),
    {
      name: "estacion-html",
      writeBundle() {
        const js = readFileSync(resolve(import.meta.dirname, "dist/app.js"), "utf8").replace(/<\/script/gi, "<\\/script");
        const css = readFileSync(resolve(import.meta.dirname, "dist/style.css"), "utf8");
        writeFileSync(
          resolve(import.meta.dirname, "..", "estacion.html"),
          `<!doctype html>\n<!-- Generated by bun run ui:build. Edit ui/src instead. -->\n<html lang="es"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta name="theme-color" content="#101112"><title>MU Slow · Capitan</title><style>${css}</style></head><body><div id="root"></div><script>${js}</script></body></html>`,
        );
      },
    },
  ],
}));
