import { defineConfig } from "vite";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

// Standalone HTML keeps the existing HTTP routes and running bot processes intact.
export default defineConfig({
  root: resolve(import.meta.dirname),
  define: { "process.env.NODE_ENV": JSON.stringify("production") },
  server: {
    host: "127.0.0.1",
    proxy: {
      "/api": {
        target: "http://127.0.0.1:8787",
        changeOrigin: true,
        headers: { origin: "http://127.0.0.1:8787" },
      },
    },
  },
  build: {
    outDir: "dist",
    emptyOutDir: true,
    cssCodeSplit: false,
    lib: {
      entry: resolve(import.meta.dirname, "src/main.tsx"),
      name: "MuStation",
      formats: ["iife"],
      cssFileName: "style",
      fileName: () => "app.js",
    },
    rolldownOptions: {
      onwarn(warning, warn) {
        if (warning.code !== "MODULE_LEVEL_DIRECTIVE") warn(warning);
      },
    },
  },
  plugins: [
    {
      name: "standalone-panels",
      writeBundle() {
        const js = readFileSync(
          resolve(import.meta.dirname, "dist/app.js"),
          "utf8",
        ).replace(/<\/script/gi, "<\\/script");
        const css = readFileSync(
          resolve(import.meta.dirname, "dist/style.css"),
          "utf8",
        );
        for (const [file, surface] of [
          ["estacion.html", "station"],
          ["panel.html", "panel"],
        ]) {
          writeFileSync(
            resolve(import.meta.dirname, "..", file!),
            `<!doctype html>\n<!-- Generated by bun run ui:build. Edit ui/src instead. -->\n<html lang="es"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta name="theme-color" content="#101113"><title>MU · ${surface === "station" ? "Estación" : "Personaje"}</title><style>${css}</style></head><body data-surface="${surface}"><div id="root"></div><script>${js}</script></body></html>`,
          );
        }
      },
    },
  ],
});
